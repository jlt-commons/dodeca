(ns dodeca.lattice.lsystem.grammar
  "The A5 curve's L-system grammar: the motif rules and the string operations
  that expand them. This is the source of truth for the curve's definition and
  is purely symbolic: the turtle geometry that interprets the symbols lives in
  turtle, and the compilation to descent tables in tables.

  7 self-referential motifs over the alphabet {A B C M P Q R} (+ their
  lowercase reverses) + the draw terminals {E e S s U u D d T t} + the 60°
  turns +/-. A LOWERCASE motif is its uppercase counterpart REVERSED,
  generated by `reverse-motif`, so only the 7 uppercase rules are authored.

  Rule tables are maps from a motif character to its string, in A5's key
  order (array maps keep it).")

(def rules
  "Each motif's production rule (the 7 authored motifs)."
  (array-map \A "PQAB"
             \B "B+++PQ---A"
             \C "P---RMb+++"
             \M "qQ+++C---b"
             \P "PpB---B+++"
             \Q "PQ---Cb+++"
             \R "b+++a---qQ"))

(def draws
  "Each motif's leaf draw symbol: the terminal it renders as at the base case."
  (array-map \A "E" \B "+e-" \C "-e+" \M "T" \P "S" \Q "D" \R "+++D---"))

(defn- swap-case [c]
  (if (Character/isLowerCase c) (Character/toUpperCase c) (Character/toLowerCase c)))

(defn reverse-motif
  "The reverse of a motif/draw string, traced end to start: reverse the
  order, swap the case of every letter (uppercase<->lowercase =
  forward<->reverse partner), and flip every `+`/`-`. This is how the
  lowercase motifs are derived from the authored uppercase rules."
  [s]
  (apply str (map (fn [c] (case c \+ \- \- \+ (swap-case c))) (reverse s))))

(defn expand-once
  "One expansion pass over `s`: replace each symbol using `table` (rules or
  draws). A lowercase motif whose uppercase is in `table` expands to that rule
  REVERSED; turns and unknown symbols pass through unchanged."
  [s table]
  (apply str (map (fn [ch]
                    (let [up (Character/toUpperCase ch)]
                      (cond
                        (contains? table ch) (get table ch)
                        (and (not= ch up) (contains? table up)) (reverse-motif (get table up))
                        :else (str ch))))
                  s)))
